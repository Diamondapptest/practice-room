export function clampState(s, init) {
  const out = {};
  for (const k of STATE_KEYS) {
    const v = Number(s?.[k]);
    out[k] = Number.isFinite(v) ? Math.max(0, Math.min(100, Math.round(v))) : init[k];
  }
  return out;
}

